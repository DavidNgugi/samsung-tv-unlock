#!/usr/bin/env bash
# Guided setup for a new TV.
#
#   tools/setup.sh
#   tools/setup.sh --tv 192.168.1.20 --profile my-cert --bridge http://192.168.1.50:8795
#   tools/setup.sh --tv 192.168.1.20 --profile my-cert --no-spotify
#
# Writes apps/Launcher/config.js, builds with the chosen certificate profile, and
# installs. Spotify is optional; without a bridge the widget simply stays hidden.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TV_IP=""; PROFILE=""; BRIDGE=""; NO_SPOTIFY=0

while [ $# -gt 0 ]; do
  case "$1" in
    --tv) TV_IP="${2:-}"; shift 2 ;;
    --profile) PROFILE="${2:-}"; shift 2 ;;
    --bridge) BRIDGE="${2:-}"; shift 2 ;;
    --no-spotify) NO_SPOTIFY=1; shift ;;
    -h|--help) sed -n '2,10p' "$0"; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 1 ;;
  esac
done

export PATH="$HOME/tizen-studio/tools:$HOME/tizen-studio/tools/ide/bin:$PATH"
command -v tizen >/dev/null || { echo "tizen CLI not found in PATH" >&2; exit 1; }
command -v sdb >/dev/null || { echo "sdb not found in PATH" >&2; exit 1; }

if [ -z "$TV_IP" ]; then
  read -r -p "TV IP address: " TV_IP
fi
[ -n "$TV_IP" ] || { echo "a TV IP is required" >&2; exit 1; }

echo "connecting to $TV_IP:26101"
sdb connect "$TV_IP:26101" >/dev/null 2>&1 || true
if ! sdb devices | grep -q "$TV_IP"; then
  echo "TV not connected. Check the IP, and that the TV allows developer mode." >&2
  sdb devices >&2
  exit 1
fi

if [ -z "$PROFILE" ]; then
  echo
  echo "certificate profiles:"
  tizen security-profiles list 2>/dev/null | sed 's/^/  /'
  read -r -p "profile name: " PROFILE
fi
[ -n "$PROFILE" ] || { echo "a profile is required" >&2; exit 1; }

if [ "$NO_SPOTIFY" -eq 0 ] && [ -z "$BRIDGE" ]; then
  DEFAULT_BRIDGE=""
  if command -v ipconfig >/dev/null; then
    LAN_IP="$(ipconfig getifaddr en0 2>/dev/null || true)"
    [ -n "${LAN_IP:-}" ] && DEFAULT_BRIDGE="http://$LAN_IP:8795"
  fi
  if [ -n "$DEFAULT_BRIDGE" ]; then
    read -r -p "Spotify bridge URL [$DEFAULT_BRIDGE, blank to skip]: " BRIDGE
    BRIDGE="${BRIDGE:-$DEFAULT_BRIDGE}"
  else
    read -r -p "Spotify bridge URL (blank to skip): " BRIDGE
  fi
fi
if [ "$NO_SPOTIFY" -eq 1 ]; then BRIDGE=""; fi

cat > "$ROOT/apps/Launcher/config.js" <<CONFIG_EOF
/* Generated by tools/setup.sh. Re-run setup to change it. */
window.TV_CONFIG = {
  spotifyUrl: "$BRIDGE"
};
CONFIG_EOF
echo "config: ${BRIDGE:-Spotify disabled}"

echo "building with profile $PROFILE"
PROFILE="$PROFILE" "$ROOT/tools/deploy-launcher.sh"

echo
echo "installed. Next:"
echo "  - press Home on the TV and open Clean Home"
if [ -n "$BRIDGE" ]; then
  echo "  - run the bridge on the machine at $BRIDGE:"
  echo "      SPOTIFY_CLIENT_ID=xxx tools/install-spotify-service.sh"
  echo "  - then complete OAuth once: http://127.0.0.1:8795/login"
else
  echo "  - Spotify disabled; edit config.js and rebuild later if wanted"
fi
